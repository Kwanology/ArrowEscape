/**
 * Keeps the largest 4-connected component so the silhouette is clean and gap-free.
 */
function keepLargestComponent(cells: Point[]): Point[] {
  const cellSet = new Set<string>(cells.map((c) => pointKey(c.x, c.y)));
  const visited = new Set<string>();
  let bestComp: Point[] = [];
  const dirs = [
    [1, 0],
    [-1, 0],
    [0, 1],
    [0, -1],
  ];

  for (const start of cells) {
    const startKey = pointKey(start.x, start.y);
    if (visited.has(startKey)) continue;

    const comp: Point[] = [];
    const queue: Point[] = [start];
    visited.add(startKey);

    while (queue.length > 0) {
      const curr = queue.shift()!;
      comp.push(curr);
      for (const [dx, dy] of dirs) {
        const nx = curr.x + dx;
        const ny = curr.y + dy;
        const nk = pointKey(nx, ny);
        if (cellSet.has(nk) && !visited.has(nk)) {
          visited.add(nk);
          queue.push({ x: nx, y: ny });
        }
      }
    }

    if (comp.length > bestComp.length) {
      bestComp = comp;
    }
  }

  return bestComp;
}

/**
 * Prunes single-pixel stairstep artifacts (cells with < 2 orthogonal neighbors)
 * produced by nearest-neighbor scaling, keeping 2x shapes smooth and tileable.
 */
function pruneSinglePixelSpikes(cells: Point[]): Point[] {
  const set = new Set<string>(cells.map((c) => pointKey(c.x, c.y)));
  let changed = true;
  while (changed) {
    changed = false;
    for (const key of Array.from(set)) {
      const comma = key.indexOf(',');
      const x = Number(key.slice(0, comma));
      const y = Number(key.slice(comma + 1));
      let deg = 0;
      if (set.has(pointKey(x + 1, y))) deg++;
      if (set.has(pointKey(x - 1, y))) deg++;
      if (set.has(pointKey(x, y + 1))) deg++;
      if (set.has(pointKey(x, y - 1))) deg++;
      if (deg < 2) {
        set.delete(key);
        changed = true;
      }
    }
  }
  const out: Point[] = [];
  for (const key of set) {
    const comma = key.indexOf(',');
    out.push({ x: Number(key.slice(0, comma)), y: Number(key.slice(comma + 1)) });
  }
  return out;
}

/**
 * Scales a bitmap cleanly onto target (cols, rows) at 2x resolution,
 * ensuring 4-connectivity and no 1-pixel spikes for zero-gap arrow tiling.
 */
export function rasterizeTemplate(
  template: SilhouetteTemplate,
  targetCols: number,
  targetRows: number
): Point[] {
  const srcRows = template.bitmap.length;
  const srcCols = template.bitmap[0].length;
  const cells: Point[] = [];

  for (let y = 0; y < targetRows; y++) {
    const sy = Math.min(srcRows - 1, Math.floor((y / targetRows) * srcRows));
    const rowStr = template.bitmap[sy];
    for (let x = 0; x < targetCols; x++) {
      const sx = Math.min(srcCols - 1, Math.floor((x / targetCols) * srcCols));
      if (rowStr[sx] === '#') {
        cells.push({ x, y });
      }
    }
  }
  return keepLargestComponent(pruneSinglePixelSpikes(cells));
}

export function getSilhouetteForLevel(
  difficulty: Difficulty,
  levelId: number
): { name: string; cols: number; rows: number; cells: Point[] } {
  const idx = levelId - 1;
  const progress = idx / 99;

  if (difficulty === 'easy') {
    const template = SMALL_TEMPLATES[idx % SMALL_TEMPLATES.length];
    // 2x resolution: 16x14 -> 20x18
    const cols = Math.round(16 + progress * 4);
    const rows = Math.round(14 + progress * 4);
    return {
      name: template.name,
      cols,
      rows,
      cells: rasterizeTemplate(template, cols, rows),
    };
  }

  if (difficulty === 'medium') {
    const template = MEDIUM_TEMPLATES[idx % MEDIUM_TEMPLATES.length];
    // 2x resolution: 22x20 -> 28x26
    const cols = Math.round(22 + progress * 6);
    const rows = Math.round(20 + progress * 6);
    return {
      name: template.name,
      cols,
      rows,
      cells: rasterizeTemplate(template, cols, rows),
    };
  }

  // Hard 2x resolution: 28x24 -> 34x30
  const template = LARGE_TEMPLATES[idx % LARGE_TEMPLATES.length];
  const cols = Math.round(28 + progress * 6);
  const rows = Math.round(24 + progress * 6);
  return {
    name: template.name,
    cols,
    rows,
    cells: rasterizeTemplate(template, cols, rows),
  };
}

export function getDailySilhouette(
  slotId: number
): { name: string; cols: number; rows: number; cells: Point[] } {
  const idx = Math.max(0, slotId - 1);
  // Cycle across Medium and Small templates scaled to 2x Medium dimensions (22x20 .. 28x26)
  const pool = [...MEDIUM_TEMPLATES, ...SMALL_TEMPLATES];
  const template = pool[idx % pool.length];
  const step = ((slotId * 13) % 37) / 36;
  const cols = Math.round(22 + step * 6);
  const rows = Math.round(20 + step * 6);
  return {
    name: template.name,
    cols,
    rows,
    cells: rasterizeTemplate(template, cols, rows),
  };
}
